export function AdminSidebar() {
  const pathname = usePathname();
  const collapsed = useAdminStore((s) => s.sidebarCollapsed);
  const mobileOpen = useAdminStore((s) => s.sidebarMobileOpen);
  const setMobileOpen = useAdminStore((s) => s.setSidebarMobileOpen);

  return (
    <>
      {mobileOpen && (
        <div
          className="fixed inset-0 z-40 bg-black/50 lg:hidden"
          onClick={() => setMobileOpen(false)}
        />
      )}
      <aside
        className={cn(
          'fixed left-0 top-16 z-50 flex h-[calc(100vh-4rem)] flex-col border-r bg-background transition-all duration-300',
          collapsed ? 'w-16' : 'w-60',
          'max-lg:fixed max-lg:top-0 max-lg:h-screen max-lg:z-50 max-lg:pt-16',
          mobileOpen ? 'max-lg:translate-x-0' : 'max-lg:-translate-x-full',
        )}
      >
        <nav className="flex-1 space-y-1 overflow-y-auto p-3">
          {NAV_ITEMS.map((item) => {
            const isDashboard = item.href === '/admin';
            const normalizedPathname = pathname.replace(/\/+$/, '') || '/';
            const normalizedHref = item.href.replace(/\/+$/, '') || '/';
            const isExactMatch = normalizedPathname === normalizedHref;
            const isPrefixMatch = !isDashboard && normalizedPathname.startsWith(normalizedHref + '/');
            const active = isExactMatch || isPrefixMatch;
            return (
              <Link
                key={item.href}
                href={item.href}
                onClick={() => setMobileOpen(false)}
                className={cn(
                  'flex items-center gap-3 rounded-lg px-3 py-2 text-sm font-medium transition-colors',
                  active
                    ? 'bg-primary text-primary-foreground'
                    : 'text-muted-foreground hover:bg-muted hover:text-foreground',
                )}
                title={collapsed ? item.label : undefined}
              >
                <svg width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="1.5" strokeLinecap="round" strokeLinejoin="round" className="shrink-0">
                  <path d={item.icon} />
                </svg>
                {!collapsed && <span>{item.label}</span>}
              </Link>
            );
          })}
        </nav>
        <div className="border-t p-3">
          <p className="text-center text-xs text-muted-foreground">
            {collapsed ? 'v1' : 'Admin v1.0'}
          </p>
        </div>
      </aside>
    </>
  );
}

export function AdminHeader() {
  const toggleSidebar = useAdminStore((s) => s.toggleSidebar);
  const collapsed = useAdminStore((s) => s.sidebarCollapsed);
  const setMobileOpen = useAdminStore((s) => s.setSidebarMobileOpen);
  const { theme, toggleTheme } = useTheme();

  return (
    <header className="sticky top-0 z-40 flex h-16 items-center gap-4 border-b bg-background px-4 sm:px-6">
      <button
        onClick={toggleSidebar}
        className="hidden h-8 w-8 items-center justify-center rounded-md transition-colors hover:bg-muted lg:flex"
        aria-label={collapsed ? 'Expand sidebar' : 'Collapse sidebar'}
      >
        <svg width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round">
          <path d={collapsed ? 'M9 18l6-6-6-6' : 'M15 18l-6-6 6-6'} />
        </svg>
      </button>
      <button
        onClick={() => setMobileOpen(true)}
        className="flex h-8 w-8 items-center justify-center rounded-md transition-colors hover:bg-muted lg:hidden"
        aria-label="Open menu"
      >
        <svg width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round">
          <path d="M3 12h18M3 6h18M3 18h18" />
        </svg>
      </button>
      <div className="flex-1" />
      <button
        onClick={toggleTheme}
        className="flex h-8 w-8 items-center justify-center rounded-md transition-colors hover:bg-muted"
        aria-label={theme === 'dark' ? 'Switch to light mode' : 'Switch to dark mode'}
      >
        {theme === 'dark' ? (
          <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round">
            <circle cx="12" cy="12" r="5"/><path d="M12 1v2M12 21v2M4.22 4.22l1.42 1.42M18.36 18.36l1.42 1.42M1 12h2M21 12h2M4.22 19.78l1.42-1.42M18.36 5.64l1.42-1.42"/>
          </svg>
        ) : (
          <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round">
            <path d="M21 12.79A9 9 0 1111.21 3 7 7 0 0021 12.79z"/>
          </svg>
        )}
      </button>
    </header>
  );
}
